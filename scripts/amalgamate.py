#!/usr/bin/env python3
"""Regenerate single_header/symnet_native_single.cpp from include/symnet/*.hpp and src/main.cpp.

    python3 scripts/amalgamate.py

The result is a self-contained translation unit (the symnet_cli program):
    g++ -std=c++17 -O3 -march=native -o symnet_cli single_header/symnet_native_single.cpp
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
ORDER = ["Common", "MatrixEngine", "AST", "Lexer", "Parser", "Compiler",
         "Runtime", "Interpreter", "WordEval", "Examples"]
LOCAL_INCLUDE = re.compile(r'^\s*#include\s+(?:"[^"]+"|<symnet/[^>]+>)\s*\n', re.M)


def strip(text: str) -> str:
    return LOCAL_INCLUDE.sub("", text.replace("#pragma once\n", ""))


parts = ["// symnet_native_single.cpp - single-file amalgamation of SymNet (the symnet_cli program).\n"
         "// GENERATED by scripts/amalgamate.py from include/symnet/*.hpp and src/main.cpp: do not edit.\n"
         "// Build: g++ -std=c++17 -O3 -march=native -o symnet_cli symnet_native_single.cpp\n"]
for name in ORDER:
    body = (ROOT / "include" / "symnet" / f"{name}.hpp").read_text()
    parts.append(f"\n// ===================== symnet/{name}.hpp =====================\n{strip(body)}")
parts.append("\n// ===================== src/main.cpp =====================\n" + strip((ROOT / "src" / "main.cpp").read_text()))

out = ROOT / "single_header" / "symnet_native_single.cpp"
out.write_text("".join(parts))
print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size} bytes)")
